def init_db():
    """Очищает старые данные и строит таблицы с чистого листа."""
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    
    cursor.execute("PRAGMA foreign_keys = OFF;")

    # Чтение декларативной структуры базы данных из файла schema.sql
    with open(SQL_PATH, "r", encoding="utf-8") as f:
        sql_script = f.read()
        
    cursor.execute("DROP TABLE IF EXISTS schedule;")
    cursor.execute("DROP TABLE IF EXISTS users;")
    cursor.execute("DROP TABLE IF EXISTS academy_contacts;")
    cursor.execute("DROP TABLE IF EXISTS classrooms;")
    cursor.execute("DROP TABLE IF EXISTS groups;")
    cursor.execute("DROP TABLE IF EXISTS specialties;")
    cursor.execute("DROP TABLE IF EXISTS bookings;")

    # Восстановление внешних ключей и пакетное выполнение SQL-скрипта схемы
    cursor.execute("PRAGMA foreign_keys = ON;")
    cursor.executescript(sql_script)
    
    # Динамическая модернизация: Изолированное добавление колонки дня недели учебного процесса
    try:
        cursor.execute("ALTER TABLE schedule ADD COLUMN day_of_week TEXT;")
    except sqlite3.OperationalError:
        pass  # Если колонка уже создана, просто идем дальше
        
    conn.commit()
    conn.close()


